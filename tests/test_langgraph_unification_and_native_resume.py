"""Comprehensive Verification Suite for LangGraph Execution Unification & Native Checkpoint Resumption.

Tests:
1. Unified single-step task routing through LangGraph for all 6 previously bypassing tasks:
   - SEARCH_FILES
   - DRAFT_MAIL
   - READ_MAIL
   - SEARCH_MAIL
   - WRITE_NOTE
   - WEB_SEARCH
   Verifies:
   - Valid 1-step plan generated by AutonomousPlanner
   - Execution strictly controlled by LangGraphExecutionEngine
   - Observations, verifications, and audit trails recorded
   - Checkpoints persisted to SQLite checkpoint store with thread_id == task.id
2. Native approval interrupt and resumption from checkpoint:
   - Reaching approval gate causes LangGraph __interrupt__
   - Task state persisted at interrupt checkpoint
   - Native resumption via orchestrator.approve(approved=True) using Command(resume=...)
   - Thread ID and checkpoint continuity verified (no restarting from scratch)
   - Resumed execution executes tool, verifies result, and records verified completion
3. Approval rejection:
   - orchestrator.approve(approved=False) resumes graph with {"approved": False}
   - Graph transitions to cancel_task node and terminates in CANCELLED status safely
4. Cryptographic approval security:
   - Modified parameters invalidate approval
   - Replay attack rejected
5. Non-agentic separation:
   - Conversational questions and direct answers do not generate task graph plans
"""

