    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.temp_dir = self.tmp.name
        self.db_path = str(Path(self.temp_dir) / "test.sqlite3")
        self.checkpoint_db = str(Path(self.temp_dir) / "checkpoints.sqlite3")
        self.memory = EncryptedMemoryStore(self.db_path)
        self.task_store = TaskStore(self.db_path)
        self.device = DeviceAutomation(dry_run=True)
        self.orchestrator = CortexOrchestrator(
            automation=self.device,
            memory=self.memory,
            task_store=self.task_store,
            dry_run=True,
        )
        self.orchestrator.execution_engine = LangGraphExecutionEngine(
            registry=self.orchestrator.registry,
            policy_engine=self.orchestrator.policy_engine,
            db_path=self.checkpoint_db,
        )

    def _count_checkpoints_for_task(self, task_id: str) -> int:
        if not os.path.exists(self.checkpoint_db):
            return 0
        conn = sqlite3.connect(self.checkpoint_db)
        cur = conn.cursor()
        cur.execute("SELECT COUNT(*) FROM checkpoints WHERE thread_id = ?", (task_id,))
        count = cur.fetchone()[0]
        conn.close()
        return count

