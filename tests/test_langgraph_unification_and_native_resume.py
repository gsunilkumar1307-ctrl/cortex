    # ──────────────────────────────────────────────────────────────────────────
    # 2. Native Approval Checkpoint Resumption & Rejection
    # ──────────────────────────────────────────────────────────────────────────

    def test_07_native_approval_checkpoint_resumption(self):
        """When approval is required, execution pauses at interrupt, and orchestrator.approve(True) resumes graph natively."""
        draft = EmailDraft(
            recipient="lead@example.com",
            subject="Production Deployment",
            body="Deployment ready for signoff.",
            sender_account="me@example.com",
        )
        approval_hash = draft.compute_hash()

        task = Task(
            intent="Send email to lead@example.com regarding Production Deployment",
            command=TaskCommand.SEND_MAIL,
            params={
                "recipient": "lead@example.com",
                "subject": "Production Deployment",
                "body": "Deployment ready for signoff.",
                "sender_account": "me@example.com",
                "approval_hash": approval_hash,
            },
            requires_approval=True,
            risk_level=RiskLevel.HIGH,
        )
        task.plan = self.orchestrator.planner.plan(task.intent, task.command, task.params, task.context)

        # 1. Execute task up to interrupt
        self.orchestrator.execution_engine.execute_plan(task)

        # Must pause at WAITING_APPROVAL
        self.assertEqual(task.status, TaskStatus.WAITING_APPROVAL)
        self.assertTrue(self.orchestrator.execution_engine.is_interrupted(task))

        # Checkpoints must be persisted at interrupt state
        initial_checkpoints = self._count_checkpoints_for_task(task.id)
        self.assertGreater(initial_checkpoints, 0)

        # 2. Approve via orchestrator.approve()
        self.orchestrator.tasks[task.id] = task
        self.orchestrator._pending_tasks[task.id] = task
        approve_result = self.orchestrator.approve(task.id, approved=True, approval_hash=approval_hash)

        # Task must be COMPLETED
        self.assertEqual(approve_result["status"], TaskStatus.COMPLETED.value)
        self.assertEqual(task.status, TaskStatus.COMPLETED)
        self.assertFalse(self.orchestrator.execution_engine.is_interrupted(task))
        self.assertTrue(task.params.get("approval_consumed"))

        # Verify that execution progressed without error
        resumed_checkpoints = self._count_checkpoints_for_task(task.id)
        self.assertGreaterEqual(resumed_checkpoints, initial_checkpoints)

    def test_08_approval_rejection_cancels_graph_cleanly(self):
        """When approval is rejected, graph resumes into cancel_task and exits safely with CANCELED status."""
        draft = EmailDraft(
            recipient="client@example.com",
            subject="Invoice #1234",
            body="Invoice attached.",
        )
        approval_hash = draft.compute_hash()

        task = Task(
            intent="Send email to client@example.com regarding Invoice",
            command=TaskCommand.SEND_MAIL,
            params={
                "recipient": "client@example.com",
                "subject": "Invoice #1234",
                "body": "Invoice attached.",
                "approval_hash": approval_hash,
            },
            requires_approval=True,
            risk_level=RiskLevel.HIGH,
        )
        task.plan = self.orchestrator.planner.plan(task.intent, task.command, task.params, task.context)

        # Run up to interrupt
        self.orchestrator.execution_engine.execute_plan(task)
        self.assertEqual(task.status, TaskStatus.WAITING_APPROVAL)
        self.assertTrue(self.orchestrator.execution_engine.is_interrupted(task))

        # User rejects
        self.orchestrator.tasks[task.id] = task
        self.orchestrator._pending_tasks[task.id] = task
        reject_result = self.orchestrator.approve(task.id, approved=False)

        self.assertIn(reject_result["status"], (TaskStatus.CANCELED.value, TaskStatus.CANCELLED.value))
        self.assertIn("rejected", task.result.lower())
        self.assertFalse(self.orchestrator.execution_engine.is_interrupted(task))

    def test_09_modified_parameters_invalidate_approval(self):
        """Modifying draft parameters after approval request invalidates the approval token."""
        draft = EmailDraft(recipient="vendor@example.com", subject="Payment", body="100 USD")
        original_hash = draft.compute_hash()

        task = Task(
            intent="Send payment email",
            command=TaskCommand.SEND_MAIL,
            params={
                "recipient": "vendor@example.com",
                "subject": "Payment",
                "body": "100 USD",
                "approval_hash": original_hash,
            },
            requires_approval=True,
            risk_level=RiskLevel.HIGH,
        )
        task.plan = self.orchestrator.planner.plan(task.intent, task.command, task.params, task.context)

        self.orchestrator.execution_engine.execute_plan(task)
        self.assertEqual(task.status, TaskStatus.WAITING_APPROVAL)

        # Attacker modifies body before approving
        task.params["body"] = "10,000 USD (tampered)"
        self.orchestrator.tasks[task.id] = task
        self.orchestrator._pending_tasks[task.id] = task

        # User attempts to approve using original hash
        result = self.orchestrator.approve(task.id, approved=True, approval_hash=original_hash)
        self.assertEqual(result["status"], TaskStatus.WAITING_APPROVAL.value)
        self.assertIn("modified", result.get("error", "").lower())

